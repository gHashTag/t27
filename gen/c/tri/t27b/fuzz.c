uint64_t atom_val(Module* m, Frame* fr, uint32_t a) {
    if ((m->ek[a] == A_PARAM)) {
        return fr->p[m->ev[a]];
    }
    if ((m->ek[a] == A_LOCAL)) {
        return fr->l[m->ev[a]];
    }
    return m->ev[a];
}

Eval eval_expr(Module* m, Frame* fr, uint32_t f, uint32_t g, bool shadow) {
    __auto_type t = m->fty[f];
    uint64_t acc = atom_val(m, fr, (g * MAX_AT));
    uint32_t i = 1;
    while ((i < m->en[g])) {
        uint32_t a = ((g * MAX_AT) + i);
        uint8_t op = m->eop[a];
        if (shadow) {
            if ((m->fkeep[f] == a)) {
                if ((op <= OP_MUL)) {
                    op = (op + 3);
                }
            }
        }
        __auto_type e = apply(op, acc, atom_val(m, fr, a), t);
        if ((e.hz != HZ_NONE)) {
            return (Eval){ .v = 0, .hz = HZ_TRAP, .at = a };
        }
        acc = e.v;
        i += 1;
    }
    return (Eval){ .v = acc, .hz = HZ_NONE, .at = 0 };
}

Eval run_fn(Module* m, uint32_t f, bool shadow) {
    __auto_type fr = (Frame){ .p = { [0 ... (3) - 1] = 0 }, .l = { [0 ... (6) - 1] = 0 }, .cnt = { [0 ... (32) - 1] = 0 } };
    uint32_t i = 0;
    while ((i < m->fnp[f])) {
        fr.p[i] = m->farg[((f * MAX_PAR) + i)];
        i += 1;
    }
    __auto_type base = (f * MAX_ST);
    __auto_type t = m->fty[f];
    uint32_t pc = 0;
    while ((pc < m->fns[f])) {
        __auto_type s = (base + pc);
        __auto_type k = m->sk[s];
        if ((k == S_RET)) {
            return eval_expr(m, &fr, f, m->sx[s], shadow);
        }
        if ((k <= S_ASSIGN)) {
            __auto_type e = eval_expr(m, &fr, f, m->sx[s], shadow);
            if ((e.hz != HZ_NONE)) {
                return e;
            }
            fr.l[m->sa[s]] = e.v;
            pc += 1;
        }
        if ((k == S_IF)) {
            __auto_type x = eval_expr(m, &fr, f, m->sx[s], shadow);
            if ((x.hz != HZ_NONE)) {
                return x;
            }
            __auto_type y = eval_expr(m, &fr, f, m->sy[s], shadow);
            if ((y.hz != HZ_NONE)) {
                return y;
            }
            if (compare(m->sa[s], x.v, y.v, t)) {
                pc += 1;
            } else {
                pc = (m->sm[s] + 1);
            }
        }
        if ((k == S_ELSE)) {
            pc = (m->sm[s] + 1);
        }
        if ((k == S_LOOP)) {
            fr.cnt[pc] = 0;
            pc += 1;
        }
        if ((k == S_END)) {
            __auto_type o = m->sm[s];
            if ((m->sk[(base + o)] == S_LOOP)) {
                fr.cnt[o] += 1;
                if ((fr.cnt[o] < m->sa[(base + o)])) {
                    pc = (o + 1);
                } else {
                    pc += 1;
                }
            } else {
                pc += 1;
            }
        }
    }
    return (Eval){ .v = 0, .hz = HZ_SHAPE, .at = 0 };
}

void settle(Module* m, uint32_t f, bool keep) {
    m->fkeep[f] = NONE;
    m->ftrap[f] = 0;
    __auto_type e = run_fn(m, f, true);
    uint32_t rounds = 0;
    while ((e.hz == HZ_TRAP)) {
        if ((rounds > 800)) {
            e = (Eval){ .v = 0, .hz = HZ_SHAPE, .at = 0 };
        } else {
            settle_step(m, f, keep, e.at);
            e = run_fn(m, f, true);
            rounds += 1;
        }
    }
    m->fv[f] = e.v;
    if ((m->fkeep[f] != NONE)) {
        __auto_type real = run_fn(m, f, false);
        if ((real.hz == HZ_TRAP)) {
            if ((real.at == m->fkeep[f])) {
                m->ftrap[f] = 1;
            }
        }
    }
}

void settle_step(Module* m, uint32_t f, bool keep, uint32_t at) {
    if (keep) {
        if ((m->fkeep[f] == NONE)) {
            m->fkeep[f] = at;
            return ;
        }
    }
    m->eop[at] = (m->eop[at] + 3);
}

void gen_case(uint64_t seed, uint64_t case_no, Module* m) {
    __auto_type r = rng_for(seed, case_no);
    m->seed = seed;
    m->case_no = case_no;
    m->nfn = ((uint32_t)((1 + rng_below(&r, MAX_FN))));
    uint32_t f = 0;
    while ((f < m->nfn)) {
        gen_fn(m, &r, f);
        bool keep = (rng_below(&r, 4) == 0);
        settle(m, f, keep);
        f += 1;
    }
}

uint32_t trap_count(Module* m) {
    uint32_t n = 0;
    uint32_t f = 0;
    while ((f < m->nfn)) {
        n += m->ftrap[f];
        f += 1;
    }
    return n;
}

bool case_ok(Module* m) {
    uint32_t f = 0;
    while ((f < m->nfn)) {
        __auto_type sh = run_fn(m, f, true);
        if ((sh.hz != HZ_NONE)) {
            return false;
        }
        if ((sh.v != m->fv[f])) {
            return false;
        }
        __auto_type real = run_fn(m, f, false);
        if ((m->ftrap[f] == 1)) {
            if ((real.hz != HZ_TRAP)) {
                return false;
            }
            if ((real.at != m->fkeep[f])) {
                return false;
            }
        } else {
            if ((real.hz != HZ_NONE)) {
                return false;
            }
            if ((real.v != m->fv[f])) {
                return false;
            }
        }
        f += 1;
    }
    return true;
}

Out out_empty(void) {
    return (Out){ .buf = { [0 ... (16384) - 1] = 0 }, .len = 0, .over = false };
}

void put(Out* o, uint8_t c) {
    if ((o->len >= OUT_CAP)) {
        o->over = true;
        return ;
    }
    o->buf[o->len] = c;
    o->len += 1;
}

void put_str(Out* o, uint8_t* s, uint32_t n) {
    uint32_t i = 0;
    while ((i < n)) {
        put(o, s[i]);
        i += 1;
    }
}

void put_u64(Out* o, uint64_t v) {
    uint8_t tmp[20] = { [0 ... (20) - 1] = 0 };
    uint32_t n = 0;
    uint64_t x = v;
    if ((x == 0)) {
        put(o, 48);
        return ;
    }
    while ((x > 0)) {
        tmp[n] = ((uint8_t)((48 + (x % 10))));
        x = (x / 10);
        n += 1;
    }
    while ((n > 0)) {
        n -= 1;
        put(o, tmp[n]);
    }
}

void put_type(Out* o, uint8_t t) {
    if (ty_signed(t)) {
        put(o, 105);
    } else {
        put(o, 117);
    }
    put_u64(o, ty_bits(t));
}

void put_const(Out* o, uint64_t v, uint8_t t) {
    __auto_type bits = ty_bits(t);
    __auto_type sg = sign_of(bits);
    if (ty_signed(t)) {
        if (((v & sg) != 0)) {
            uint64_t mag = ((0 - v) & mask_of(bits));
            put_str(o, "(-", 2);
            if ((mag == sg)) {
                put_u64(o, (sg - 1));
                put_str(o, " - 1)", 5);
                return ;
            }
            put_u64(o, mag);
            put(o, 41);
            return ;
        }
    }
    put_u64(o, v);
}

void put_atom(Out* o, Module* m, uint32_t f, uint32_t a) {
    if ((m->ek[a] == A_PARAM)) {
        put(o, 112);
        put_u64(o, m->ev[a]);
        return ;
    }
    if ((m->ek[a] == A_LOCAL)) {
        put(o, 118);
        put_u64(o, m->ev[a]);
        return ;
    }
    if ((m->eop[a] == OP_SHLK)) {
        put_u64(o, m->ev[a]);
        return ;
    }
    if ((m->eop[a] == OP_SHRK)) {
        put_u64(o, m->ev[a]);
        return ;
    }
    put_const(o, m->ev[a], m->fty[f]);
}

void put_op(Out* o, uint8_t op) {
    if ((op == OP_ADD)) {
        put_str(o, " + ", 3);
    }
    if ((op == OP_SUB)) {
        put_str(o, " - ", 3);
    }
    if ((op == OP_MUL)) {
        put_str(o, " * ", 3);
    }
    if ((op == OP_ADDW)) {
        put_str(o, " +% ", 4);
    }
    if ((op == OP_SUBW)) {
        put_str(o, " -% ", 4);
    }
    if ((op == OP_MULW)) {
        put_str(o, " *% ", 4);
    }
    if ((op == OP_AND)) {
        put_str(o, " & ", 3);
    }
    if ((op == OP_OR)) {
        put_str(o, " | ", 3);
    }
    if ((op == OP_XOR)) {
        put_str(o, " ^ ", 3);
    }
    if ((op == OP_SHLK)) {
        put_str(o, " << ", 4);
    }
    if ((op == OP_SHRK)) {
        put_str(o, " >> ", 4);
    }
    if ((op == OP_SHLV)) {
        put_str(o, " << (", 5);
    }
    if ((op == OP_SHRV)) {
        put_str(o, " >> (", 5);
    }
    if ((op == OP_DIV)) {
        put_str(o, " / (", 4);
    }
    if ((op == OP_REM)) {
        put_str(o, " % (", 4);
    }
}

void put_expr(Out* o, Module* m, uint32_t f, uint32_t g) {
    __auto_type n = m->en[g];
    uint32_t i = 1;
    while ((i < n)) {
        put(o, 40);
        i += 1;
    }
    put_atom(o, m, f, (g * MAX_AT));
    i = 1;
    while ((i < n)) {
        uint32_t a = ((g * MAX_AT) + i);
        __auto_type op = m->eop[a];
        put_op(o, op);
        put_atom(o, m, f, a);
        if ((op >= OP_SHLV)) {
            if ((op <= OP_SHRV)) {
                put_str(o, " & ", 3);
                put_u64(o, (ty_bits(m->fty[f]) - 1));
                put(o, 41);
            } else {
                put_str(o, " | 1)", 5);
            }
        }
        put(o, 41);
        i += 1;
    }
}

void put_cmp(Out* o, uint32_t c) {
    if ((c == C_LT)) {
        put_str(o, " < ", 3);
    }
    if ((c == C_GT)) {
        put_str(o, " > ", 3);
    }
    if ((c == C_LE)) {
        put_str(o, " <= ", 4);
    }
    if ((c == C_GE)) {
        put_str(o, " >= ", 4);
    }
    if ((c == C_EQ)) {
        put_str(o, " == ", 4);
    }
    if ((c == C_NE)) {
        put_str(o, " != ", 4);
    }
}

void put_indent(Out* o, uint32_t depth) {
    uint32_t i = 0;
    while ((i < depth)) {
        put_str(o, "    ", 4);
        i += 1;
    }
}

void put_fn(Out* o, Module* m, uint32_t f) {
    __auto_type base = (f * MAX_ST);
    __auto_type t = m->fty[f];
    put_str(o, "fn f", 4);
    put_u64(o, f);
    put(o, 40);
    uint32_t i = 0;
    while ((i < m->fnp[f])) {
        if ((i > 0)) {
            put_str(o, ", ", 2);
        }
        put(o, 112);
        put_u64(o, i);
        put_str(o, ": ", 2);
        put_type(o, t);
        i += 1;
    }
    put_str(o, ") -> ", 5);
    put_type(o, t);
    put_str(o, " {", 2);
    put(o, 10);
    uint32_t depth = 1;
    uint32_t pc = 0;
    while ((pc < m->fns[f])) {
        __auto_type s = (base + pc);
        __auto_type k = m->sk[s];
        if ((k == S_DECL)) {
            put_indent(o, depth);
            put_str(o, "var v", 5);
            put_u64(o, m->sa[s]);
            put_str(o, ": ", 2);
            put_type(o, t);
            put_str(o, " = ", 3);
            put_expr(o, m, f, m->sx[s]);
            put(o, 59);
            put(o, 10);
        }
        if ((k == S_ASSIGN)) {
            put_indent(o, depth);
            put(o, 118);
            put_u64(o, m->sa[s]);
            put_str(o, " = ", 3);
            put_expr(o, m, f, m->sx[s]);
            put(o, 59);
            put(o, 10);
        }
        if ((k == S_IF)) {
            put_indent(o, depth);
            put_str(o, "if (", 4);
            put_expr(o, m, f, m->sx[s]);
            put_cmp(o, m->sa[s]);
            put_expr(o, m, f, m->sy[s]);
            put_str(o, ") {", 3);
            put(o, 10);
            depth += 1;
        }
        if ((k == S_ELSE)) {
            put_indent(o, (depth - 1));
            put_str(o, "} else {", 8);
            put(o, 10);
        }
        if ((k == S_LOOP)) {
            put_indent(o, depth);
            put_str(o, "var k", 5);
            put_u64(o, pc);
            put_str(o, ": u32 = 0;", 10);
            put(o, 10);
            put_indent(o, depth);
            put_str(o, "while (k", 8);
            put_u64(o, pc);
            put_str(o, " < ", 3);
            put_u64(o, m->sa[s]);
            put_str(o, ") {", 3);
            put(o, 10);
            depth += 1;
        }
        if ((k == S_END)) {
            __auto_type op = m->sm[s];
            if ((m->sk[(base + op)] == S_LOOP)) {
                put_indent(o, depth);
                put(o, 107);
                put_u64(o, op);
                put_str(o, " += 1;", 6);
                put(o, 10);
            }
            depth -= 1;
            put_indent(o, depth);
            put(o, 125);
            put(o, 10);
        }
        if ((k == S_RET)) {
            put_indent(o, depth);
            put_str(o, "return ", 7);
            put_expr(o, m, f, m->sx[s]);
            put(o, 59);
            put(o, 10);
        }
        pc += 1;
    }
    put(o, 125);
    put(o, 10);
    put(o, 10);
}

void put_test(Out* o, Module* m, uint32_t f) {
    __auto_type t = m->fty[f];
    put_str(o, "test f", 6);
    put_u64(o, f);
    if ((m->ftrap[f] == 1)) {
        put_str(o, "_expect_trap {", 14);
    } else {
        put_str(o, "_expect_pass {", 14);
    }
    put(o, 10);
    put_str(o, "    const checksum: ", 20);
    put_type(o, t);
    put_str(o, " = f", 4);
    put_u64(o, f);
    put(o, 40);
    uint32_t i = 0;
    while ((i < m->fnp[f])) {
        if ((i > 0)) {
            put_str(o, ", ", 2);
        }
        put_const(o, m->farg[((f * MAX_PAR) + i)], t);
        i += 1;
    }
    put_str(o, ");", 2);
    put(o, 10);
    put_str(o, "    assert_eq(checksum, ", 24);
    put_const(o, m->fv[f], t);
    put_str(o, ");", 2);
    put(o, 10);
    put(o, 125);
    put(o, 10);
    put(o, 10);
}

void render_case(Module* m, Out* o) {
    put_str(o, "; t27b fuzz case -- seed ", 25);
    put_u64(o, m->seed);
    put_str(o, " case ", 6);
    put_u64(o, m->case_no);
    put_str(o, " (gHashTag/t27#6442)", 20);
    put(o, 10);
    put_str(o, "module FuzzCase;", 16);
    put(o, 10);
    put(o, 10);
    uint32_t f = 0;
    while ((f < m->nfn)) {
        put_fn(o, m, f);
        f += 1;
    }
    f = 0;
    while ((f < m->nfn)) {
        put_test(o, m, f);
        f += 1;
    }
}

bool fuzz_render(uint64_t seed, uint64_t case_no, Out* o) {
    __auto_type m = module_empty(seed, case_no);
    gen_case(seed, case_no, &m);
    o->len = 0;
    o->over = false;
    render_case(&m, o);
    if (o->over) {
        return false;
    }
    return case_ok(&m);
}

uint64_t digest(Out* o) {
    uint64_t h = 0xCBF29CE484222325;
    uint32_t i = 0;
    while ((i < o->len)) {
        h = ((h ^ o->buf[i]) * 0x100000001B3);
        i += 1;
    }
    return h;
}

bool line_is(Out* o, uint32_t k, uint8_t* s, uint32_t n) {
    uint32_t i = 0;
    uint32_t line = 0;
    while ((line < k)) {
        if ((i >= o->len)) {
            return false;
        }
        if ((o->buf[i] == 10)) {
            line += 1;
        }
        i += 1;
    }
    uint32_t j = 0;
    while ((j < n)) {
        if ((i >= o->len)) {
            return false;
        }
        if ((o->buf[i] != s[j])) {
            return false;
        }
        i += 1;
        j += 1;
    }
    if ((i >= o->len)) {
        return false;
    }
    return (o->buf[i] == 10);
}


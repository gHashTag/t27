void test_kept_trap_checksum_is_the_wrapped_value(void) {
    __auto_type m = module_empty(1, 2);
    m.nfn = 1;
    m.fty[0] = 0;
    m.fnp[0] = 1;
    m.farg[0] = 200;
    __auto_type d0 = emit(&m, 0, S_DECL);
    m.sx[d0] = first_expr(&m, 0);
    __auto_type ret = emit(&m, 0, S_RET);
    m.sx[ret] = 1;
    m.nex[0] = 2;
    m.en[1] = 2;
    m.ek[4] = A_LOCAL;
    m.ev[4] = 0;
    m.eop[5] = OP_ADD;
    m.ek[5] = A_CONST;
    m.ev[5] = 100;
    settle(&m, 0, true);
    assert((m.ftrap[0] == 1));
    assert((m.fv[0] == 44));
    assert((m.eop[5] == OP_ADD));
    assert(case_ok(&m));
    __auto_type n = module_empty(1, 2);
    n.nfn = 1;
    n.fty[0] = 0;
    n.fnp[0] = 1;
    n.farg[0] = 200;
    __auto_type e0 = emit(&n, 0, S_DECL);
    n.sx[e0] = first_expr(&n, 0);
    __auto_type r2 = emit(&n, 0, S_RET);
    n.sx[r2] = 1;
    n.nex[0] = 2;
    n.en[1] = 2;
    n.ek[4] = A_LOCAL;
    n.ev[4] = 0;
    n.eop[5] = OP_ADD;
    n.ek[5] = A_CONST;
    n.ev[5] = 100;
    settle(&n, 0, false);
    assert((n.ftrap[0] == 0));
    assert((n.eop[5] == OP_ADDW));
    assert((n.fv[0] == 44));
}



//! BitNet HLS engine-top emitter (Wave 36f, R-BN-6).
//!
//! Exposes a single emitter:
//!
//!   * `bitnet_engine_top` -- the top-level wrapper that turns the
//!     compute / buffering / I/O blocks emitted in W36a..W36e into a
//!     complete multi-layer BitNet inference engine. The wrapper
//!     instantiates a `multilayer_sequencer` (high-level layer-driver
//!     FSM) and a `double_buffer_ctrl` (ping-pong activation storage)
//!     and adds a 32-bit free-running cycle counter gated by `busy`
//!     so the host can profile inference latency.
//!
//! Port summary:
//!
//! | Group         | Signals                                                |
//! |---------------|--------------------------------------------------------|
//! | Clock / reset | clk, rst_n                                             |
//! | Control       | start, num_layers[5:0], neurons_per_layer[15:0],       |
//! |               | chunks_per_neuron[7:0], signed threshold[15:0]         |
//! | External mem  | mem_addr[31:0], mem_rd_en, mem_rd_data[63:0],          |
//! |               | mem_rd_valid                                           |
//! | Status        | busy, done, cycle_count[31:0]                          |
//!
//! Note: the emitted Verilog references two sub-modules by name --
//! `multilayer_sequencer` and `double_buffer_ctrl`. The latter is
//! produced by the W36c `gen-double-buffer-ctrl` emitter. The former
//! is currently expected from the upstream vibee-lang library and is
//! left as a black-box reference here; the rest of the engine-top is
//! self-contained.
//!
//! Algorithm ported from `gHashTag/vibee-lang`
//! `src/vibeec/verilog_codegen.zig` lines 1667-1725
//! (`writeBitNetEngineTop`). Original author: Dmitrii Vasilev.
//!
//! Constitutional notes:
//!   L2: lives only under `bootstrap/`; emitter is a pure additive
//!       string builder; no edits under `gen/`, `coq/`, `trios-coq/`,
//!       `proofs/`, `specs/`, `conformance/`, `architecture/`,
//!       `rings/`, or root `Cargo.toml`.
//!   L3: ASCII source, English doc-comments only.
//!   L5: numeric kernel untouched -- this emitter is a structural
//!       wrapper; it does not redefine any constant inside the
//!       trinity invariant `phi^2 + 1/phi^2 = 3`.
//!   L7: no `*.sh` invoked.

/// Default identifier for the engine-top module.
pub const DEFAULT_BITNET_ENGINE_TOP_NAME: &str = "bitnet_engine_top";

fn is_valid_verilog_ident(s: &str) -> bool {
    let mut chars = s.chars();
    let first = match chars.next() {
        Some(c) => c,
        None => return false,
    };
    if !(first.is_ascii_alphabetic() || first == '_') {
        return false;
    }
    chars.all(|c| c.is_ascii_alphanumeric() || c == '_')
}

fn resolve_ident<'a>(candidate: &'a str, default: &'a str) -> &'a str {
    if is_valid_verilog_ident(candidate) {
        candidate
    } else {
        default
    }
}

/// Build the `bitnet_engine_top` SystemVerilog module text.
///
/// Parameters:
///   * `module_name` -- Verilog identifier; falls back to
///     `bitnet_engine_top` if the candidate is not a valid Verilog
///     identifier (must start with `[A-Za-z_]` and contain only
///     `[A-Za-z0-9_]`).
pub fn build_bitnet_engine_top(module_name: &str) -> String {
    let name = resolve_ident(module_name, DEFAULT_BITNET_ENGINE_TOP_NAME);
    let mut s = String::new();

    s.push_str("// ===========================================================================\n");
    s.push_str("// BITNET INFERENCE ENGINE TOP - Complete multi-layer inference\n");
    s.push_str("// ===========================================================================\n");
    s.push_str("// Generated by t27c gen-bitnet-engine-top (Wave 36f, R-BN-6).\n");
    s.push_str("// Wraps multilayer_sequencer + double_buffer_ctrl + cycle counter\n");
    s.push_str("// into a host-startable multi-layer BitNet inference engine.\n");
    s.push_str("\n");

    s.push_str(&format!("module {} (\n", name));
    s.push_str("    input  wire        clk,\n");
    s.push_str("    input  wire        rst_n,\n");
    s.push_str("    input  wire        start,\n");
    s.push_str("    input  wire [5:0]  num_layers,\n");
    s.push_str("    input  wire [15:0] neurons_per_layer,\n");
    s.push_str("    input  wire [7:0]  chunks_per_neuron,\n");
    s.push_str("    input  wire signed [15:0] threshold,\n");
    s.push_str("    // External memory interface (simplified)\n");
    s.push_str("    output wire [31:0] mem_addr,\n");
    s.push_str("    output wire        mem_rd_en,\n");
    s.push_str("    input  wire [63:0] mem_rd_data,\n");
    s.push_str("    input  wire        mem_rd_valid,\n");
    s.push_str("    // Status\n");
    s.push_str("    output wire        busy,\n");
    s.push_str("    output wire        done,\n");
    s.push_str("    output wire [31:0] cycle_count\n");
    s.push_str(");\n");
    s.push_str("\n");

    s.push_str("    // Multi-layer sequencer\n");
    s.push_str("    wire [5:0] current_layer;\n");
    s.push_str("    wire layer_start, layer_done, start_prefetch, prefetch_done;\n");
    s.push_str("    multilayer_sequencer seq (\n");
    s.push_str("        .clk(clk), .rst_n(rst_n), .start(start), .num_layers(num_layers),\n");
    s.push_str("        .layer_done(layer_done), .prefetch_done(prefetch_done),\n");
    s.push_str("        .current_layer(current_layer), .layer_start(layer_start),\n");
    s.push_str("        .start_prefetch(start_prefetch), .inference_done(done)\n");
    s.push_str("    );\n");
    s.push_str("\n");

    s.push_str("    // Double buffer controller\n");
    s.push_str("    wire use_buffer_a;\n");
    s.push_str("    wire [11:0] buf_read_addr, buf_write_addr;\n");
    s.push_str("    double_buffer_ctrl dbl_buf (\n");
    s.push_str("        .clk(clk), .rst_n(rst_n), .layer_done(layer_done),\n");
    s.push_str("        .current_layer(current_layer), .use_buffer_a(use_buffer_a),\n");
    s.push_str("        .read_addr(buf_read_addr), .write_addr(buf_write_addr), .neuron_id(12'd0)\n");
    s.push_str("    );\n");
    s.push_str("\n");

    // Busy / cycle counter
    // `busy` must be high for the entire inference, starting on `start`
    // and dropping when the multilayer_sequencer asserts `done`. Deriving
    // it from `(current_layer != 0) || layer_start` (the previous form)
    // misses the first layer almost entirely: layer 0 has
    // `current_layer == 0`, and `layer_start` is a 1-cycle pulse, so the
    // cycle counter stalled while layer 0 was running.
    s.push_str("    // Busy tracker: high from `start` until top-level `done`.\n");
    s.push_str("    reg started;\n");
    s.push_str("    always @(posedge clk or negedge rst_n) begin\n");
    s.push_str("        if (!rst_n)      started <= 1'b0;\n");
    s.push_str("        else if (done)   started <= 1'b0;\n");
    s.push_str("        else if (start)  started <= 1'b1;\n");
    s.push_str("    end\n");
    s.push_str("    assign busy = started && !done;\n");
    s.push_str("\n");
    s.push_str("    // Cycle counter\n");
    s.push_str("    reg [31:0] cycles;\n");
    s.push_str("    always @(posedge clk or negedge rst_n)\n");
    s.push_str("        if (!rst_n) cycles <= 32'd0;\n");
    s.push_str("        else if (start) cycles <= 32'd0;\n");
    s.push_str("        else if (busy) cycles <= cycles + 32'd1;\n");
    s.push_str("    assign cycle_count = cycles;\n");
    s.push_str("\n");

    s.push_str("    // External memory port currently unused at this level; sub-modules\n");
    s.push_str("    // drive it in higher-fidelity assemblies. Tie off the explicit\n");
    s.push_str("    // outputs so synthesis does not infer X-drivers.\n");
    s.push_str("    assign mem_addr  = 32'd0;\n");
    s.push_str("    assign mem_rd_en = 1'b0;\n");
    s.push_str("\n");

    s.push_str("endmodule\n");

    s
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn ident_validator_basics() {
        assert!(is_valid_verilog_ident("bitnet_engine_top"));
        assert!(is_valid_verilog_ident("a"));
        assert!(is_valid_verilog_ident("_x"));
        assert!(is_valid_verilog_ident("Foo123"));
        assert!(!is_valid_verilog_ident(""));
        assert!(!is_valid_verilog_ident("9foo"));
        assert!(!is_valid_verilog_ident("has space"));
        assert!(!is_valid_verilog_ident("dash-name"));
        assert!(!is_valid_verilog_ident("uni\u{00e9}"));
    }

    #[test]
    fn default_name_used_when_invalid() {
        let v = build_bitnet_engine_top("");
        assert!(v.contains("module bitnet_engine_top ("));
        let v2 = build_bitnet_engine_top("9bad");
        assert!(v2.contains("module bitnet_engine_top ("));
    }

    #[test]
    fn custom_name_propagates() {
        let v = build_bitnet_engine_top("engine_top_v1");
        assert!(v.contains("module engine_top_v1 ("));
        assert!(!v.contains("module bitnet_engine_top ("));
    }

    #[test]
    fn control_ports_present() {
        let v = build_bitnet_engine_top(DEFAULT_BITNET_ENGINE_TOP_NAME);
        for port in [
            "input  wire        start,",
            "input  wire [5:0]  num_layers,",
            "input  wire [15:0] neurons_per_layer,",
            "input  wire [7:0]  chunks_per_neuron,",
            "input  wire signed [15:0] threshold,",
        ] {
            assert!(v.contains(port), "missing control port `{}`", port);
        }
    }

    #[test]
    fn status_ports_present() {
        let v = build_bitnet_engine_top(DEFAULT_BITNET_ENGINE_TOP_NAME);
        assert!(v.contains("output wire        busy,"));
        assert!(v.contains("output wire        done,"));
        assert!(v.contains("output wire [31:0] cycle_count"));
    }

    #[test]
    fn external_memory_ports_present() {
        let v = build_bitnet_engine_top(DEFAULT_BITNET_ENGINE_TOP_NAME);
        assert!(v.contains("output wire [31:0] mem_addr,"));
        assert!(v.contains("output wire        mem_rd_en,"));
        assert!(v.contains("input  wire [63:0] mem_rd_data,"));
        assert!(v.contains("input  wire        mem_rd_valid,"));
    }

    #[test]
    fn multilayer_sequencer_instance() {
        let v = build_bitnet_engine_top(DEFAULT_BITNET_ENGINE_TOP_NAME);
        assert!(v.contains("multilayer_sequencer seq ("));
        assert!(v.contains(".current_layer(current_layer)"));
        assert!(v.contains(".inference_done(done)"));
    }

    #[test]
    fn double_buffer_instance() {
        let v = build_bitnet_engine_top(DEFAULT_BITNET_ENGINE_TOP_NAME);
        assert!(v.contains("double_buffer_ctrl dbl_buf ("));
        assert!(v.contains(".use_buffer_a(use_buffer_a)"));
        assert!(v.contains(".neuron_id(12'd0)"));
    }

    #[test]
    fn cycle_counter_logic() {
        let v = build_bitnet_engine_top(DEFAULT_BITNET_ENGINE_TOP_NAME);
        assert!(v.contains("reg [31:0] cycles;"));
        assert!(v.contains("if (!rst_n) cycles <= 32'd0;"));
        assert!(v.contains("else if (start) cycles <= 32'd0;"));
        assert!(v.contains("else if (busy) cycles <= cycles + 32'd1;"));
        assert!(v.contains("assign cycle_count = cycles;"));
    }

    #[test]
    fn busy_tracks_start_to_done_w88() {
        // Regression for W88: previously
        //   assign busy = (current_layer != 6'd0) || layer_start;
        // which missed layer 0 entirely (current_layer == 0 the whole
        // time, layer_start is a 1-cycle pulse), so the cycle counter
        // stalled. The fixed form latches a `started` flag from `start`
        // and clears it on top-level `done`.
        let v = build_bitnet_engine_top(DEFAULT_BITNET_ENGINE_TOP_NAME);
        assert!(v.contains("reg started;"));
        assert!(v.contains("else if (done)   started <= 1'b0;"));
        assert!(v.contains("else if (start)  started <= 1'b1;"));
        assert!(v.contains("assign busy = started && !done;"));
        // Old buggy form must be gone.
        assert!(!v.contains("assign busy = (current_layer != 6'd0) || layer_start;"));
    }


    #[test]
    fn external_memory_outputs_tied_off() {
        let v = build_bitnet_engine_top(DEFAULT_BITNET_ENGINE_TOP_NAME);
        assert!(v.contains("assign mem_addr  = 32'd0;"));
        assert!(v.contains("assign mem_rd_en = 1'b0;"));
    }

    #[test]
    fn module_ends_with_endmodule() {
        let v = build_bitnet_engine_top(DEFAULT_BITNET_ENGINE_TOP_NAME);
        assert!(v.trim_end().ends_with("endmodule"));
    }

    #[test]
    fn emitted_text_is_pure_ascii() {
        let v = build_bitnet_engine_top(DEFAULT_BITNET_ENGINE_TOP_NAME);
        assert!(v.is_ascii(), "emitted Verilog must be ASCII");
    }
}

#!/usr/bin/env python3
"""W748: emit the sparse ternary layer as TRUTH TABLES, the LogicNets form.

The point of the exercise: a neuron with fan-in F over W-bit inputs is a
function of F*W bits. Written as a case statement over those bits, yosys maps it
into LUT6s directly -- no adder tree, no weight registers, no threshold
comparator. The arithmetic vanishes into the table.

The table is generated by EVALUATING the neuron over all 2^(F*W) input patterns,
so the emitted hardware is by construction the same function the trainer scored.
That is the whole guarantee, and it is why the table is generated rather than
written by hand.
"""
import argparse, random, sys

def neuron_table(weights, thr, in_bits):
    """weights: list of F ints (ternary levels). Returns 2^(F*in_bits) -> 2-bit sym."""
    F = len(weights)
    out = []
    for pat in range(1 << (F * in_bits)):
        acc = 0
        for j in range(F):
            v = (pat >> (j * in_bits)) & ((1 << in_bits) - 1)
            # 1-bit input is bipolar {-1,+1}; 2-bit input is ternary {-1,0,+1}
            x = (1 if v else -1) if in_bits == 1 else (0 if v == 0 else (1 if v == 1 else -1))
            acc += weights[j] * x
        out.append(1 if acc > thr else (3 if acc < -thr else 0))
    return out

def emit(n_in, n_out, fanin, in_bits, seed, levels):
    rnd = random.Random(seed)
    lines = ["`default_nettype none",
             f"// sparse ternary layer: {n_out} neurons, fan-in {fanin}, {in_bits}-bit inputs",
             f"// each neuron is a truth table over {fanin*in_bits} bits -> 2-bit ternary symbol",
             f"module sparse_layer (",
             f"    input  wire [{n_in*in_bits-1}:0] x,",
             f"    output wire [{2*n_out-1}:0] sym",
             ");"]
    for o in range(n_out):
        picks = rnd.sample(range(n_in), min(fanin, n_in))
        w = [rnd.choice(levels) for _ in picks]
        tbl = neuron_table(w, thr=2, in_bits=in_bits)
        sel = ", ".join(f"x[{p*in_bits+b}]" for p in reversed(picks) for b in reversed(range(in_bits)))
        lines.append(f"    wire [{len(picks)*in_bits-1}:0] s{o} = {{{sel}}};")
        lines.append(f"    reg [1:0] r{o};")
        lines.append(f"    always @* case (s{o})")
        # Group by output value so the case is compact; default covers the rest.
        from collections import Counter
        common = Counter(tbl).most_common(1)[0][0]
        for pat, v in enumerate(tbl):
            if v != common:
                lines.append(f"        {len(picks)*in_bits}'d{pat}: r{o} = 2'd{v};")
        lines.append(f"        default: r{o} = 2'd{common};")
        lines.append("    endcase")
        lines.append(f"    assign sym[{2*o+1}:{2*o}] = r{o};")
    lines.append("endmodule")
    return "\n".join(lines)

if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("-n", type=int, default=593); ap.add_argument("-m", type=int, default=64)
    ap.add_argument("--fanin", type=int, default=6); ap.add_argument("--inbits", type=int, default=1)
    ap.add_argument("--seed", type=int, default=1)
    a = ap.parse_args()
    print(emit(a.n, a.m, a.fanin, a.inbits, a.seed, [-4,-2,-1,1,2,4]))
